// Extracts exact Paperlogy outlines for the display words of the film and writes
// src/generated/glyphs.ts. Each glyph keeps its contours separately so a component
// can drop one (e.g. the ㅇ of 입 that the hero disc replaces).
//   node scripts/build-glyphs.mjs
import opentype from 'opentype.js';
import fs from 'node:fs';

const WEIGHTS = { black: 'public/fonts/Paperlogy-9Black.ttf', extrabold: 'public/fonts/Paperlogy-8ExtraBold.ttf' };
const TEXT = '사입삼춘.요청확보미송전달수령기록함께';

const load = (f) => {
  const b = fs.readFileSync(f);
  return opentype.parse(b.buffer.slice(b.byteOffset, b.byteOffset + b.byteLength));
};

const r = (n) => Math.round(n * 10) / 10;
const out = {};
for (const [name, file] of Object.entries(WEIGHTS)) {
  const font = load(file);
  const glyphs = {};
  for (const ch of new Set(TEXT)) {
    const g = font.charToGlyph(ch);
    const p = g.getPath(0, 0, font.unitsPerEm);
    const contours = [];
    let cur = null;
    for (const c of p.commands) {
      if (c.type === 'M') { cur = { d: '', pts: [] }; contours.push(cur); }
      if (c.type === 'M') cur.d += `M${r(c.x)} ${r(c.y)}`;
      else if (c.type === 'L') cur.d += `L${r(c.x)} ${r(c.y)}`;
      else if (c.type === 'Q') cur.d += `Q${r(c.x1)} ${r(c.y1)} ${r(c.x)} ${r(c.y)}`;
      else if (c.type === 'C') cur.d += `C${r(c.x1)} ${r(c.y1)} ${r(c.x2)} ${r(c.y2)} ${r(c.x)} ${r(c.y)}`;
      else if (c.type === 'Z') cur.d += 'Z';
      if (c.x !== undefined) cur.pts.push([c.x, c.y]);
    }
    glyphs[ch] = {
      advance: g.advanceWidth,
      contours: contours.map((ct) => {
        const xs = ct.pts.map((q) => q[0]);
        const ys = ct.pts.map((q) => q[1]);
        return { d: ct.d, box: [r(Math.min(...xs)), r(Math.min(...ys)), r(Math.max(...xs)), r(Math.max(...ys))] };
      }),
    };
  }
  out[name] = { unitsPerEm: font.unitsPerEm, glyphs };
}
fs.mkdirSync('src/generated', { recursive: true });
fs.writeFileSync(
  'src/generated/glyphs.ts',
  `// AUTO-GENERATED by scripts/build-glyphs.mjs from the Paperlogy TTFs. Do not edit.\n` +
    `export type GlyphContour = { d: string; box: [number, number, number, number] };\n` +
    `export type GlyphData = { advance: number; contours: GlyphContour[] };\n` +
    `export type GlyphFont = { unitsPerEm: number; glyphs: Record<string, GlyphData> };\n` +
    `export const GLYPHS: Record<'black' | 'extrabold', GlyphFont> = ${JSON.stringify(out)};\n`,
);
console.log('wrote', Object.keys(out.black.glyphs).length, 'glyphs x', Object.keys(out).length, 'weights', fs.statSync('src/generated/glyphs.ts').size, 'bytes');
