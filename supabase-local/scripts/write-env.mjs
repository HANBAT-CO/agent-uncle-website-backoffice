#!/usr/bin/env node
// Write the LOCAL stack's connection settings into two gitignored files:
//
//   supabase-local/.env.seed.local   URL + publishable key + LOCAL service-role key.
//                                    Read only by supabase-local/seed/*.mjs. Never by Next.js.
//   .env.development.local           A clearly fenced BACKOFFICE_LOCAL block with the LOCAL URL and
//                                    publishable key only (no service key). Existing lines outside
//                                    the block are kept. Next.js loads this file for `next dev` only.
//
// The landing's NEXT_PUBLIC_SUPABASE_* (live project, in .env.local) are NOT touched or overridden:
// the backoffice uses its own BACKOFFICE_* names.
// Usage: node supabase-local/scripts/write-env.mjs   (stack must be running)

import { execFileSync } from "node:child_process";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const localRoot = resolve(here, "..");
const repoRoot = resolve(localRoot, "..");

const status = JSON.parse(
  execFileSync(join(here, "sb.sh"), ["status", "--output", "json"], { encoding: "utf8", stdio: ["ignore", "pipe", "ignore"] }),
);
const url = status.API_URL;
if (!/^http:\/\/(127\.0\.0\.1|localhost):55321$/.test(url)) throw new Error(`refusing: ${url} is not the local backoffice stack`);
for (const k of ["PUBLISHABLE_KEY", "SERVICE_ROLE_KEY", "DB_URL", "STUDIO_URL"]) if (!status[k]) throw new Error(`status is missing ${k}`);

const seedEnv = `# LOCAL ONLY, gitignored (.env* rule). Generated by supabase-local/scripts/write-env.mjs.
# Used only by supabase-local/seed/*.mjs. Never copy these values into Next.js env files or Vercel.
LOCAL_SUPABASE_URL=${url}
LOCAL_SUPABASE_PUBLISHABLE_KEY=${status.PUBLISHABLE_KEY}
LOCAL_SUPABASE_SERVICE_ROLE_KEY=${status.SERVICE_ROLE_KEY}
LOCAL_SUPABASE_DB_URL=${status.DB_URL}
`;
writeFileSync(join(localRoot, ".env.seed.local"), seedEnv, { mode: 0o600 });

const BEGIN = "# >>> BACKOFFICE_LOCAL >>>";
const END = "# <<< BACKOFFICE_LOCAL <<<";
const block = `${BEGIN}
# Generated by supabase-local/scripts/write-env.mjs. LOCAL Supabase stack for /admin development.
# Public values only (publishable key). No service-role key here, ever.
BACKOFFICE_SUPABASE_TARGET=local
BACKOFFICE_SUPABASE_URL=${url}
BACKOFFICE_SUPABASE_PUBLISHABLE_KEY=${status.PUBLISHABLE_KEY}
NEXT_PUBLIC_BACKOFFICE_SUPABASE_URL=${url}
NEXT_PUBLIC_BACKOFFICE_SUPABASE_PUBLISHABLE_KEY=${status.PUBLISHABLE_KEY}
${END}`;
const devFile = join(repoRoot, ".env.development.local");
let dev = existsSync(devFile) ? readFileSync(devFile, "utf8") : "";
const re = new RegExp(`${BEGIN.replace(/[.*+?^${}()|[\]\\]/g, "\\$&")}[\\s\\S]*?${END.replace(/[.*+?^${}()|[\]\\]/g, "\\$&")}`);
dev = re.test(dev) ? dev.replace(re, block) : `${dev}${dev && !dev.endsWith("\n") ? "\n" : ""}${dev ? "\n" : ""}${block}\n`;
if (/SERVICE_ROLE|sb_secret_/i.test(dev.replace(/#[^\n]*/g, ""))) throw new Error("refusing: a secret key would end up in .env.development.local");
writeFileSync(devFile, dev);

console.log(`wrote supabase-local/.env.seed.local (seed scripts only) and the BACKOFFICE_LOCAL block in .env.development.local`);
console.log(`  API ${url}   Studio ${status.STUDIO_URL}   DB ${status.DB_URL.replace(/:[^:@/]+@/, ":****@")}`);
