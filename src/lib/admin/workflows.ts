export function workflowHref(collection: string, id: string): string {
  if (collection === "invoices")
    return `/admin/billing/${encodeURIComponent(id)}`;
  const group =
    (Object.keys(GROUPS) as WorkflowGroup[]).find((g) =>
      GROUPS[g].includes(collection as WorkflowCollection),
    ) ?? "team-work";
  return `/admin/${group}?collection=${encodeURIComponent(collection)}&related=${encodeURIComponent(id)}`;
}
