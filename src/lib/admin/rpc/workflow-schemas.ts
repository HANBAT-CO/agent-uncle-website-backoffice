export const releaseListSchema = z.object({
  total: z.number(), limit: z.number(), offset: z.number(),
  rows: z.array(z.object({
    id: z.string(), updatedAt: z.string(), root: releaseMetadataSchema,
    variantSource: z.enum(["shared", "platforms", "legacy"]),
    variants: z.object({ ios: releaseMetadataSchema.optional(), android: releaseMetadataSchema.optional() }),
    invalidVariants: z.array(z.string()),
  })),
});
export type ReleaseMetadata = z.infer<typeof releaseMetadataSchema>;
